using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;

namespace HSMServer.Model.Agent
{
    /// <summary>One entry of the Downloads page's product selector: a root product and its folder, if any.</summary>
    public sealed record DownloadProductItem(Guid Id, string Name, string FolderName)
    {
        /// <summary>The selector text: the folder is shown for orientation, as on the Products page.</summary>
        public string DisplayName => string.IsNullOrEmpty(FolderName) ? Name : $"{Name} ({FolderName})";
    }


    /// <summary>
    /// The Downloads page (#1550): the products an admin can take a bundle for, what is staged on this
    /// server for each platform, and the address the bundles will point at. The bundles themselves are
    /// still generated by <c>AgentController</c> (<c>installer</c>, <c>linux-installer</c>); this page
    /// only shows the state those endpoints will answer with.
    /// </summary>
    public sealed class DownloadsViewModel
    {
        public IReadOnlyList<DownloadProductItem> Products { get; init; } = [];

        /// <summary>The product to preselect (only when it is in <see cref="Products"/>).</summary>
        public Guid? SelectedProductId { get; init; }

        /// <summary>Whether <c>wwwroot/agent/hsm-agent.exe</c> is staged; without it the endpoint answers 503.</summary>
        public bool AgentStaged { get; init; }

        /// <summary>The staged <c>version.txt</c>, or null when it is missing or empty.</summary>
        public string AgentVersion { get; init; }

        /// <summary>The single staged probe package name, or null when the endpoint would answer 503.</summary>
        public string ProbePackage { get; init; }

        /// <summary>The probe version carried by <see cref="ProbePackage"/>'s name.</summary>
        public string ProbeVersion { get; init; }

        public bool ProbeStaged => ProbePackage is not null;

        /// <summary>The address + port both bundles bake into their config (display only).</summary>
        public string ServerAddress { get; init; }

        public int ServerPort { get; init; }

        /// <summary>Why the Linux probe endpoint would refuse this address (400), or null when it accepts it.</summary>
        public string ProbeAddressWarning { get; init; }

        public string AgentNotStagedMessage => AgentInstallerBundle.NotStagedMessage;

        public string ProbeNotStagedMessage => LinuxProbeInstallerBundle.NotStagedMessage;
    }


    /// <summary>
    /// Builds <see cref="DownloadsViewModel"/> from the visible products and the web root. Reads only what
    /// the download endpoints read (the staged files), with the same "not staged" rules, so the page never
    /// offers a button the endpoint would answer with 503.
    /// </summary>
    public static class DownloadsPageBuilder
    {
        public static DownloadsViewModel Build(IEnumerable<DownloadProductItem> products, string webRootPath,
                                               string serverAddress, int serverPort, Guid? selectedProductId = null)
        {
            var ordered = (products ?? [])
                .Where(p => p is not null)
                .GroupBy(p => p.Id)
                .Select(g => g.First())
                .OrderBy(p => p.Name, StringComparer.OrdinalIgnoreCase)
                .ThenBy(p => p.FolderName, StringComparer.OrdinalIgnoreCase)
                .ThenBy(p => p.Id)
                .ToList();

            var probePackage = FindStagedProbePackage(webRootPath);

            return new DownloadsViewModel
            {
                Products = ordered,
                SelectedProductId = selectedProductId is Guid id && ordered.Any(p => p.Id == id) ? id : null,
                AgentStaged = IsAgentStaged(webRootPath),
                AgentVersion = ReadStagedAgentVersion(webRootPath),
                ProbePackage = probePackage,
                ProbeVersion = LinuxProbeInstallerBundle.PackageVersion(probePackage),
                ServerAddress = serverAddress,
                ServerPort = serverPort,
                ProbeAddressWarning = LinuxProbeInstallerBundle.ValidateServerAddress(serverAddress),
            };
        }

        /// <summary>Whether the agent exe is staged where <c>AgentController.Installer</c> reads it.</summary>
        public static bool IsAgentStaged(string webRootPath) =>
            !string.IsNullOrEmpty(webRootPath) &&
            File.Exists(Path.Combine(webRootPath, AgentInstallerBundle.StagingFolder, AgentInstallerBundle.ExeName));

        /// <summary>The staged agent version (<c>wwwroot/agent/version.txt</c>), or null when missing, unreadable or empty.</summary>
        public static string ReadStagedAgentVersion(string webRootPath)
        {
            if (string.IsNullOrEmpty(webRootPath))
                return null;

            try
            {
                var text = File.ReadAllText(Path.Combine(webRootPath, AgentInstallerBundle.StagingFolder, AgentInstallerBundle.VersionFileName)).Trim();
                return text.Length == 0 ? null : text;
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                return null;
            }
        }

        /// <summary>The probe package <c>AgentController.LinuxInstaller</c> would serve, or null when it would answer 503.</summary>
        public static string FindStagedProbePackage(string webRootPath)
        {
            if (string.IsNullOrEmpty(webRootPath))
                return null;

            try
            {
                return LinuxProbeInstallerBundle.SelectStagedPackage(
                    Directory.EnumerateFiles(Path.Combine(webRootPath, LinuxProbeInstallerBundle.StagingFolder)));
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
            {
                return null;
            }
        }
    }
}
